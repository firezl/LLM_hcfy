function toTraditional(text) {
  return String(text).replace(/[\u4e00-\u9fff]/g, (ch) => S2T[ch] || ch);
}

function buildZhTW() {
  const out = {};
  for (const [k, v] of Object.entries(zhCN)) {
    out[k] = toTraditional(v)
      .replace(/LLM划词翻译/g, "LLM劃詞翻譯")
      .replace(/划词/g, "劃詞")
      .replace(/谷歌/g, "Google")
      .replace(/硅基流动/g, "矽基流動")
      .replace(/设置/g, "設定")
      .replace(/软件/g, "軟體")
      .replace(/程序/g, "程式")
      .replace(/服务器/g, "伺服器")
      .replace(/网络/g, "網路")
      .replace(/信息/g, "資訊")
      .replace(/默认/g, "預設")
      .replace(/鼠标/g, "滑鼠")
      .replace(/文件/g, "檔案");
  }
  return out;
}

