function buildLocale(code) {
  if (code === "zh-CN") return { ...zhCN };
  if (code === "zh-TW") return buildZhTW();
  const bundle = bundles[code];
  if (!bundle) throw new Error(`Missing locale bundle: ${code}`);
  const out = {};
  for (const key of Object.keys(zhCN)) {
    if (!(key in bundle)) {
      throw new Error(`Locale ${code} missing key: ${key}`);
    }
    out[key] = bundle[key];
  }
  for (const key of Object.keys(bundle)) {
    if (!(key in zhCN)) {
      throw new Error(`Locale ${code} has extra key: ${key}`);
    }
  }
  return out;
}

async function main() {
  await mkdir(LOCALES_DIR, { recursive: true });
  const codes = ["zh-CN", "zh-TW", "en", "ja", "ko", "fr", "de", "es", "ru", "pt"];
  const counts = {};
  for (const code of codes) {
    const data = buildLocale(code);
    const keys = Object.keys(data).sort();
    const sorted = {};
    for (const k of keys) sorted[k] = data[k];
    const file = resolve(LOCALES_DIR, `${code}.json`);
    await writeFile(file, `${JSON.stringify(sorted, null, 2)}\n`, "utf8");
    counts[code] = keys.length;
  }
  console.log("Generated locale files:");
  for (const [code, n] of Object.entries(counts)) {
    console.log(`  ${code}.json — ${n} keys`);
  }
}

await main();
