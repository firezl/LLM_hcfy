/**
 * Extracts content-script UI rules into styles/content-ui.css.
 * Run: node scripts/extract-content-ui-css.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(".");
const stylesPath = resolve(ROOT, "styles.css");
const outPath = resolve(ROOT, "styles/content-ui.css");

const css = await readFile(stylesPath, "utf8");
const lines = css.split(/\r?\n/);

const rootBlock = lines.slice(0, 27).join("\n");
const bubbleThemes = lines.slice(52, 91).join("\n");
const bubbleUi = lines.slice(154, 471).join("\n");
const btnUi = lines
    .slice(92, 153)
    .join("\n")
    .replace(/#jyt-translate-btn\.jyt-btn/g, ".jyt-btn")
    .replace(/#jyt-thought-content/g, ".jyt-thought-content");
const pdfPrompt = lines.slice(1336, 1432).join("\n");

const contentUi = `/* Content script UI (Shadow DOM) — AUTO-GENERATED by scripts/extract-content-ui-css.mjs */
${rootBlock}

${bubbleThemes}

:host {
    all: initial;
}

${btnUi}

${bubbleUi}

${pdfPrompt}
`;

await mkdir(resolve(ROOT, "styles"), { recursive: true });
await writeFile(outPath, contentUi, "utf8");
console.log(`Wrote ${outPath}`);
