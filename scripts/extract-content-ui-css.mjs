/**
 * Extracts content-script UI rules into styles/content-ui.css.
 * Run: node scripts/extract-content-ui-css.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(".");
const stylesPath = resolve(ROOT, "styles.css");
const outPath = resolve(ROOT, "styles/content-ui.css");

const css = (await readFile(stylesPath, "utf8")).replace(/\r\n/g, "\n");

function sliceBetween(text, startPattern, endPattern) {
    const start = text.indexOf(startPattern);
    if (start < 0) {
        throw new Error(`Missing CSS marker: ${startPattern}`);
    }
    const end = text.indexOf(endPattern, start + startPattern.length);
    if (end < 0) {
        throw new Error(`Missing CSS marker: ${endPattern}`);
    }
    return text.slice(start, end).trimEnd();
}

const rootBlock = sliceBetween(
    css,
    ":root {",
    "/* Dark mode — options page */",
);
const designTokens = rootBlock
    .replace(/^:root\s*\{/, "")
    .replace(/\}\s*$/, "")
    .split("\n")
    .map((line) => {
        const trimmed = line.trim();
        return trimmed ? `    ${trimmed}` : "";
    })
    .join("\n")
    .trim();

const bubbleThemes = sliceBetween(
    css,
    "/* Dark mode — translation bubble",
    "/* Translate button/bubble render inside #jyt-translate-root",
);

const btnUi = sliceBetween(
    css,
    "#jyt-translate-btn.jyt-btn {",
    ".jyt-bubble {",
).replace(/#jyt-translate-btn\.jyt-btn/g, ".jyt-btn");

const bubbleUi = sliceBetween(css, ".jyt-bubble {", "/* options page */").replace(
    /#jyt-thought-content/g,
    ".jyt-thought-content",
);

const contentUi = `/* Content script UI (Shadow DOM) — AUTO-GENERATED by scripts/extract-content-ui-css.mjs */
:host {
    all: initial;
    pointer-events: none;
${designTokens}
}

${bubbleThemes}

.jyt-btn,
.jyt-bubble {
    pointer-events: auto;
}

${btnUi}

${bubbleUi}
`;

await mkdir(resolve(ROOT, "styles"), { recursive: true });
await writeFile(outPath, contentUi, "utf8");
console.log(`Wrote ${outPath}`);
