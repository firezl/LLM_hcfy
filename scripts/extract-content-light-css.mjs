/**
 * Extracts light-DOM content-script CSS (PDF prompt, etc.) into styles/content-light.css.
 * Shadow DOM UI styles live in styles/content-ui.css (bundled into dist/content.bundle.js).
 * Run: node scripts/extract-content-light-css.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(".");
const stylesPath = resolve(ROOT, "styles.css");
const outPath = resolve(ROOT, "styles/content-light.css");

const css = (await readFile(stylesPath, "utf8")).replace(/\r\n/g, "\n");

function sliceBetween(text, startPattern, endPattern) {
    const start = text.indexOf(startPattern);
    if (start < 0) {
        throw new Error(`Missing CSS marker: ${startPattern}`);
    }
    const end = text.indexOf(endPattern, start + startPattern.length);
    if (end < 0) {
        throw new Error(`Missing CSS marker: ${endPattern}`);
    }
    return text.slice(start, end).trimEnd();
}

const rootBlock = sliceBetween(
    css,
    ":root {",
    "/* Dark mode — options page */",
);

const popInKeyframes = sliceBetween(
    css,
    "@keyframes jyt-pop-in {",
    ".jyt-header {",
);

const pdfPromptUi = sliceBetween(
    css,
    "/* content light DOM (manifest content_scripts) */",
    "/* Help page */",
);

const contentLight = `/* Light-DOM content script UI — AUTO-GENERATED by scripts/extract-content-light-css.mjs */
${rootBlock}

${popInKeyframes}

${pdfPromptUi}
`;

await mkdir(resolve(ROOT, "styles"), { recursive: true });
await writeFile(outPath, contentLight, "utf8");
console.log(`Wrote ${outPath}`);
