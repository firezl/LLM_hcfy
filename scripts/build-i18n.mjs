/**
 * Generates libs/i18n-messages.js, libs/i18n-messages.mjs, and
 * libs/i18n-content-messages.js from i18n/locales/*.json.
 * Run: node scripts/build-i18n.mjs [--check]
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const ROOT = resolve(".");
const LOCALES_DIR = resolve(ROOT, "i18n/locales");
const CONTENT_DIR = resolve(ROOT, "content");
const OUT_JS = resolve(ROOT, "libs/i18n-messages.js");
const OUT_MJS = resolve(ROOT, "libs/i18n-messages.mjs");
const OUT_CONTENT_JS = resolve(ROOT, "libs/i18n-content-messages.js");

const CONTENT_KEY_PREFIXES = [
    "bubble.",
    "langDetect.",
    "browser.translate.",
    "common.",
    "pdf",
    "contextMenu.",
    "options.engine.auto.candidate.",
];

const LITERAL_T_PATTERN =
    /(?:(?<![\w.])t|(?<![\w.])app\.t)\(\s*(['"])([^'"\\]+)\1/g;

function stableStringify(value) {
    if (Array.isArray(value)) {
        return `[${value.map(stableStringify).join(",")}]`;
    }
    if (value && typeof value === "object") {
        return `{${Object.keys(value)
            .sort()
            .map(
                (key) =>
                    `${JSON.stringify(key)}:${stableStringify(value[key])}`,
            )
            .join(",")}}`;
    }
    return JSON.stringify(value);
}

async function loadLocales() {
    const files = (await readdir(LOCALES_DIR))
        .filter((name) => name.endsWith(".json"))
        .sort();
    const messages = {};
    for (const file of files) {
        const lang = file.replace(/\.json$/, "");
        const raw = await readFile(resolve(LOCALES_DIR, file), "utf8");
        messages[lang] = JSON.parse(raw);
    }
    return messages;
}

function buildJsOutput(messages) {
    return `// AUTO-GENERATED by scripts/build-i18n.mjs — do not edit by hand.
(function (global) {
    global.JYT_I18N_MESSAGES = ${stableStringify(messages)};
})(typeof globalThis !== "undefined" ? globalThis : window);
`;
}

function buildMjsOutput(messages) {
    return `// AUTO-GENERATED by scripts/build-i18n.mjs — do not edit by hand.
export const I18N_MESSAGES = ${stableStringify(messages)};
`;
}

function buildContentJsOutput(messages) {
    return `// AUTO-GENERATED by scripts/build-i18n.mjs — do not edit by hand.
(function (global) {
    global.JYT_I18N_SCOPE = "content";
    global.JYT_I18N_MESSAGES = ${stableStringify(messages)};
})(typeof globalThis !== "undefined" ? globalThis : window);
`;
}

async function collectLiteralContentKeys() {
    const entries = await readdir(CONTENT_DIR, { recursive: true });
    const keys = new Set();
    for (const entry of entries) {
        const rel = String(entry);
        if (!rel.endsWith(".js")) {
            continue;
        }
        const source = await readFile(resolve(CONTENT_DIR, rel), "utf8");
        for (const match of source.matchAll(LITERAL_T_PATTERN)) {
            keys.add(match[2]);
        }
    }
    return keys;
}

function isContentMessageKey(key, literalKeys) {
    if (literalKeys.has(key)) {
        return true;
    }
    return CONTENT_KEY_PREFIXES.some((prefix) => key.startsWith(prefix));
}

function filterContentMessages(messages, literalKeys) {
    const filtered = {};
    for (const lang of Object.keys(messages).sort()) {
        const next = {};
        for (const [key, value] of Object.entries(messages[lang])) {
            if (isContentMessageKey(key, literalKeys)) {
                next[key] = value;
            }
        }
        filtered[lang] = next;
    }
    return filtered;
}

async function main() {
    const checkOnly = process.argv.includes("--check");
    const messages = await loadLocales();
    const literalKeys = await collectLiteralContentKeys();
    const contentMessages = filterContentMessages(messages, literalKeys);
    const jsOut = buildJsOutput(messages);
    const mjsOut = buildMjsOutput(messages);
    const contentJsOut = buildContentJsOutput(contentMessages);

    if (checkOnly) {
        const [prevJs, prevMjs, prevContentJs] = await Promise.all([
            readFile(OUT_JS, "utf8").catch(() => ""),
            readFile(OUT_MJS, "utf8").catch(() => ""),
            readFile(OUT_CONTENT_JS, "utf8").catch(() => ""),
        ]);
        if (
            prevJs !== jsOut ||
            prevMjs !== mjsOut ||
            prevContentJs !== contentJsOut
        ) {
            console.error(
                "i18n message bundles are out of date. Run: node scripts/build-i18n.mjs",
            );
            process.exit(1);
        }
        console.log("i18n message bundles are up to date");
        return;
    }

    await Promise.all([
        writeFile(OUT_JS, jsOut, "utf8"),
        writeFile(OUT_MJS, mjsOut, "utf8"),
        writeFile(OUT_CONTENT_JS, contentJsOut, "utf8"),
    ]);
    const fullBytes = Buffer.byteLength(jsOut);
    const contentBytes = Buffer.byteLength(contentJsOut);
    const sample = contentMessages.en || {};
    console.log(`Updated ${OUT_JS} (${fullBytes} bytes)`);
    console.log(`Updated ${OUT_MJS}`);
    console.log(
        `Updated ${OUT_CONTENT_JS} (${contentBytes} bytes, ${Object.keys(sample).length} keys per language)`,
    );
}

await main();
