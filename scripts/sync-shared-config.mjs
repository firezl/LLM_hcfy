/**
 * Generates libs/shared-config.js from ESM sources (single source of truth).
 * Run: node scripts/sync-shared-config.mjs [--check]
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import esbuild from "esbuild";

const ROOT = resolve(".");
const OUT_PATH = resolve(ROOT, "libs/shared-config.js");
const AUTO_ENGINE_CLIENT_PATH = resolve(ROOT, "libs/auto-engine-client.js");

function stableStringify(value) {
    if (Array.isArray(value)) {
        return `[${value.map(stableStringify).join(",")}]`;
    }
    if (value && typeof value === "object") {
        return `{${Object.keys(value)
            .sort()
            .map(
                (key) =>
                    `${JSON.stringify(key)}:${stableStringify(value[key])}`,
            )
            .join(",")}}`;
    }
    return JSON.stringify(value);
}

function formatObjectLiteral(obj, indent = 4) {
    const pad = " ".repeat(indent);
    const inner = Object.entries(obj)
        .map(([key, value]) => {
            const serialized = JSON.stringify(value);
            return `${pad}${JSON.stringify(key)}: ${serialized},`;
        })
        .join("\n");
    return `{\n${inner}\n${" ".repeat(indent - 4)}}`;
}

async function loadModule(relativePath) {
    return import(pathToFileURL(resolve(ROOT, relativePath)).href);
}

async function buildOutput() {
    const { DEFAULT_SETTINGS } = await loadModule("libs/default-settings.mjs");
    const { MESSAGE_TYPES } = await loadModule("libs/message-types.mjs");
    const registry = await loadModule("libs/engine-registry.mjs");

    const registryPayload = {
        ENGINE_DEFINITIONS: registry.ENGINE_DEFINITIONS,
        LLM_ENGINE_IDS: registry.LLM_ENGINE_IDS,
        CUSTOM_PROMPT_SETTING_BY_ENGINE:
            registry.CUSTOM_PROMPT_SETTING_BY_ENGINE,
        SYSTEM_PROMPT_SETTING_BY_ENGINE:
            registry.SYSTEM_PROMPT_SETTING_BY_ENGINE,
        USER_PROMPT_SETTING_BY_ENGINE:
            registry.USER_PROMPT_SETTING_BY_ENGINE,
        CUSTOM_HEADERS_SETTING_BY_ENGINE:
            registry.CUSTOM_HEADERS_SETTING_BY_ENGINE,
        CUSTOM_PAYLOAD_SETTING_BY_ENGINE:
            registry.CUSTOM_PAYLOAD_SETTING_BY_ENGINE,
        OPENAI_COMPAT_MODEL_ENGINES: registry.OPENAI_COMPAT_MODEL_ENGINES,
        ENGINE_SECTION_IDS: registry.ENGINE_SECTION_IDS,
    };

    return `// AUTO-GENERATED by scripts/sync-shared-config.mjs — do not edit by hand.
(function (global) {
    const DEFAULT_SETTINGS = ${formatObjectLiteral(DEFAULT_SETTINGS)};

    const MESSAGE_TYPES = ${formatObjectLiteral(MESSAGE_TYPES)};

    const ENGINE_REGISTRY = ${stableStringify(registryPayload)};

    global.JYT_SHARED = {
        DEFAULT_SETTINGS,
        MESSAGE_TYPES,
    };
    global.JYT_ENGINE_REGISTRY = ENGINE_REGISTRY;
})(typeof globalThis !== "undefined" ? globalThis : window);
`;
}

async function buildAutoEngineClient() {
    await esbuild.build({
        entryPoints: [resolve(ROOT, "libs/auto-engine.mjs")],
        outfile: AUTO_ENGINE_CLIENT_PATH,
        bundle: true,
        format: "iife",
        globalName: "JYT_AUTO_ENGINE",
        platform: "browser",
        target: ["chrome109", "firefox140"],
        banner: {
            js: "// AUTO-GENERATED by scripts/sync-shared-config.mjs — do not edit by hand.",
        },
        logLevel: "silent",
    });
    return readFile(AUTO_ENGINE_CLIENT_PATH, "utf8");
}

async function main() {
    const checkOnly = process.argv.includes("--check");
    const next = await buildOutput();
    const autoEngineClient = await buildAutoEngineClient();
    let previous = "";
    let previousAutoEngine = "";
    try {
        previous = await readFile(OUT_PATH, "utf8");
    } catch (err) {
        if (err.code !== "ENOENT") {
            throw err;
        }
    }
    try {
        previousAutoEngine = await readFile(AUTO_ENGINE_CLIENT_PATH, "utf8");
    } catch (err) {
        if (err.code !== "ENOENT") {
            throw err;
        }
    }

    if (checkOnly) {
        if (previous !== next) {
            console.error(
                "libs/shared-config.js is out of date. Run: node scripts/sync-shared-config.mjs",
            );
            process.exit(1);
        }
        if (previousAutoEngine !== autoEngineClient) {
            console.error(
                "libs/auto-engine-client.js is out of date. Run: node scripts/sync-shared-config.mjs",
            );
            process.exit(1);
        }
        console.log("libs/shared-config.js is up to date");
        return;
    }

    if (previous !== next) {
        await writeFile(OUT_PATH, next, "utf8");
        console.log("Updated libs/shared-config.js");
    } else {
        console.log("libs/shared-config.js already up to date");
    }

    if (previousAutoEngine !== autoEngineClient) {
        await writeFile(AUTO_ENGINE_CLIENT_PATH, autoEngineClient, "utf8");
        console.log("Updated libs/auto-engine-client.js");
    } else {
        console.log("libs/auto-engine-client.js already up to date");
    }
}

await main();
